github_storage = "https://raw.githubusercontent.com/FacultadInformatica-LinkedData/Curso2021-2022/master/Assignment4/course_materials"

from rdflib import Graph, Namespace, Literal, URIRef
g1 = Graph()
g2 = Graph()
g1.parse(github_storage+"/rdf/data01.rdf", format="xml")
g2.parse(github_storage+"/rdf/data02.rdf", format="xml")

"""List all the elements of the Person class in the first graph (data01.rdf) and fill in any
missing fields (given name, family name and email) using the data from the second graph
(data02.rdf). You can use SPARQL queries or iterate through the graph, or both.
"""

from rdflib.namespace import RDF
VCARD = Namespace("http://www.w3.org/2001/vcard-rdf/3.0#")
ns = Namespace("http://data.org#")

# List the individuals of Person in g1 (SPARQL)
query = """
PREFIX ns: <http://data.org#>

SELECT ?person WHERE {
  ?person a ns:Person .
}
"""
persons = [r.person for r in g1.query(query)]

print("Individuals of Person:")
for person in persons:
  print(person)

# Complete each missing field in g1 with the values found in g2 for the same individual
fields = [VCARD.Given, VCARD.Family, VCARD.EMAIL]
for person in persons:
  for field in fields:
    if g1.value(person, field) is None:
      for value in g2.objects(person, field):
        g1.add((person, field, value))

# Visualize the results
print("\nCompleted data:")
for person in persons:
  print(person, [str(g1.value(person, field)) for field in fields])
