github_storage = "https://raw.githubusercontent.com/FacultadInformatica-LinkedData/Curso2021-2022/master/Assignment4/course_materials/"

from rdflib import Graph, Namespace, Literal, URIRef
g1 = Graph()
g2 = Graph()
g3 = Graph()
g1.parse(github_storage+"rdf/data03.rdf", format="xml")
g2.parse(github_storage+"rdf/data04.rdf", format="xml")

"""Search for individuals in both graphs and link them using the OWL:sameAs property; insert
these matches into g3. We consider two individuals to be the same if they have the same first
name and surname. Please note that the URIs do not necessarily have to be the same for the same
individual in both graphs.
"""

from rdflib.namespace import OWL
VCARD = Namespace("http://www.w3.org/2001/vcard-rdf/3.0#")
g3.bind("owl", OWL)

query = """
PREFIX vcard: <http://www.w3.org/2001/vcard-rdf/3.0#>

SELECT ?person ?given ?family WHERE {
  ?person vcard:Given ?given ;
          vcard:Family ?family .
}
"""

# Index the individuals of g2 by (given name, family name)
g2_index = {}
for r in g2.query(query):
  g2_index.setdefault((str(r.given), str(r.family)), []).append(r.person)

# Link every individual of g1 with the individuals of g2 that share given and family names
for r in g1.query(query):
  for match in g2_index.get((str(r.given), str(r.family)), []):
    g3.add((r.person, OWL.sameAs, match))

# Visualize the results
for s, p, o in g3:
  print(s, p, o)
